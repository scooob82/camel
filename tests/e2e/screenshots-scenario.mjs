import { execFileSync } from 'node:child_process';
import { chromium } from 'playwright';
const base = process.env.BASE_URL, out = '/tmp/shots';
import { mkdirSync } from 'node:fs'; mkdirSync(out, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'en-US' });
const page = await ctx.newPage();
const cs = async () => { await page.evaluate(() => localStorage.setItem('cas.lang', '"cs"')); };
const shot = async (n, full=false) => { await page.waitForTimeout(500); await page.screenshot({ path: `${out}/${n}.png`, fullPage: full }); console.log('shot', n); };
const email = 'miroslav@example.com';
await page.goto(base + '#/register');
await page.locator('#email').fill(email);
await page.locator('#password').fill('a long password 9');
await page.getByRole('button', { name: 'Create account' }).click();
await page.locator('h1', { hasText: 'Projects' }).waitFor();
execFileSync('php', ['api/bin/make-admin.php', email], { env: { ...process.env, CAS_CONFIG: process.env.E2E_CONFIG } });
for (const r of ['Content-Based Router', 'Split']) {
  await page.getByRole('button', { name: '+ New project' }).first().click();
  const o = page.locator('.option', { hasText: r }).first();
  if (await o.count()) await o.click();
  await page.getByRole('button', { name: 'Create project' }).click();
  await page.locator('.studio').waitFor();
  await page.goto(base + '#/dashboard'); await page.locator('h1').waitFor();
}
await cs();
await page.goto(base + '#/'); await page.reload(); await shot('01-landing');
await page.goto(base + '#/dashboard'); await page.waitForTimeout(600); await shot('02-dashboard');
await page.locator('a[href*="builder/"]').first().click();
await page.locator('.studio').waitFor(); await shot('03-builder');
await page.locator('[role=tab]', { hasText: 'Spustit' }).click();
await page.locator('.run-panel button.primary, .run-panel button', { hasText: 'Spustit' }).first().click();
await page.locator('.trace-item').first().waitFor();
await page.locator('.trace-item').nth(1).click(); await shot('04-run-debug');
await page.goto(base + '#/lab'); await page.waitForTimeout(600);
await page.getByLabel('Engine').selectOption('saxon-xslt');
await page.locator('button', { hasText: 'Ladit' }).first().click(); await page.waitForTimeout(800); await shot('05-lab-debug');
await page.locator('[role=tab]', { hasText: 'Mapování' }).click(); await shot('06-lab-mapper');
await page.goto(base + '#/admin'); await page.locator('.stat b').first().waitFor(); await shot('07-admin');
await page.evaluate(() => localStorage.setItem('cas.theme', '"light"'));
await page.goto(base + '#/'); await page.reload(); await shot('08-landing-light');
await b.close();
